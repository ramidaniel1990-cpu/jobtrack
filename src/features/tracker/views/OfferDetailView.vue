<script setup lang="ts">
import { computed } from "vue";
import { useRoute } from "vue-router";
import { useTrackerStore } from "../store";
const route = useRoute();
const store = useTrackerStore();
const offer = computed(() =>
  store.offers.find((item) => item.id === route.params.id),
);
</script>
<template>
  <section class="detail-page">
    <RouterLink to="/offers" class="back-link">← Back to offers</RouterLink>
    <template v-if="offer">
      <div class="page-heading">
        <div>
          <p class="eyebrow">{{ offer.company }}</p>
          <h1>{{ offer.title }}</h1>
          <p>{{ offer.location }} · {{ offer.modality }}</p>
        </div>
        <span class="badge">Fictional offer</span>
      </div>
      <div class="detail-grid">
        <article class="panel detail-content">
          <h2>About the opportunity</h2>
          <p>{{ offer.description }}</p>
          <div class="tags">
            <span
              v-for="technology in offer.technologies"
              :key="technology"
              class="tag"
              >{{ technology }}</span
            >
          </div>
          <dl class="offer-facts">
            <div>
              <dt>Experience</dt>
              <dd>{{ offer.experience }}</dd>
            </div>
            <div>
              <dt>Employment type</dt>
              <dd>{{ offer.employment }}</dd>
            </div>
            <div>
              <dt>Languages</dt>
              <dd>{{ offer.languages.join(", ") }}</dd>
            </div>
            <div>
              <dt>Annual salary</dt>
              <dd>
                {{
                  offer.salary
                    ? new Intl.NumberFormat("en-GB", {
                        style: "currency",
                        currency: offer.currency,
                        maximumFractionDigits: 0,
                      }).format(offer.salary)
                    : "Not listed"
                }}
              </dd>
            </div>
            <div>
              <dt>Fictional publication date</dt>
              <dd>
                {{ new Date(offer.publishedAt).toLocaleDateString("en-GB") }}
              </dd>
            </div>
          </dl>
        </article>
        <aside class="panel detail-content">
          <span class="eyebrow">SIMULATED ASSESSMENT</span>
          <h2>Example match: {{ offer.score }}%</h2>
          <p>{{ offer.explanation }}</p>
          <p class="notice">
            This explanation is a local simulation. It is not generated by an AI
            agent and is not professional advice.
          </p>
          <div class="detail-buttons">
            <button
              class="button primary"
              @click="
                store.decide(
                  offer.id,
                  store.decisions[offer.id] === 'saved' ? undefined : 'saved',
                )
              "
            >
              {{
                store.decisions[offer.id] === "saved"
                  ? "Remove from saved"
                  : "Save offer"
              }}
</button
            ><button
              class="button"
              @click="
                store.decide(
                  offer.id,
                  store.decisions[offer.id] === 'discarded'
                    ? undefined
                    : 'discarded',
                )
              "
            >
              {{
                store.decisions[offer.id] === "discarded"
                  ? "Restore offer"
                  : "Discard offer"
              }}
            </button>
          </div>
        </aside>
      </div>
    </template>
    <div v-else class="panel empty-state">
      <h1>Offer not found</h1>
      <p>Browse available offers or run a demo search.</p>
      <RouterLink to="/offers" class="button primary">View offers</RouterLink>
    </div>
  </section>
</template>
